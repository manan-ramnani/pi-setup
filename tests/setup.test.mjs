import assert from 'node:assert/strict';
import { mkdtemp, writeFile, readFile, mkdir, rm, cp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { parseOptions, npmIdentity, mergeSettings, preflight, bootstrap } from '../scripts/bootstrap.mjs';
import { nodeSupported, root, versions, commandPath, invocation } from '../scripts/lib.mjs';
import { snapshotHash, applyCustomization } from '../scripts/install-skills.mjs';

assert(nodeSupported('22.19.0'));
assert(nodeSupported('24.0.0'));
assert(!nodeSupported('22.18.0'));
assert(!nodeSupported('20.19.0'));
assert.equal(npmIdentity('npm:@example/name@1.0.0'),'@example/name');
assert.equal(npmIdentity('npm:example@1.0.0'),'example');
assert.equal(npmIdentity('git:github.com/example/name'),undefined);
assert.throws(()=>parseOptions(['--agent-dir']),/needs a path/);
assert.throws(()=>parseOptions(['--unknown']),/Unknown option/);
assert.deepEqual(parseOptions(['--dry-run','--with-skills']).dryRun,true);
const temp=await mkdtemp(join(tmpdir(),'pi-setup-test-'));
try {
  const agent=join(temp,'agent');
  await mkdir(agent);
  const existing={defaultProvider:'custom',defaultModel:'custom-model',theme:'dark',packages:['npm:pi-agents','git:github.com/example/tools','npm:pi-ask-user@0.1.0'],defaultTools:['read','bash','write','edit']};
  const merged=mergeSettings(existing,agent,[join(agent,'.pi-setup-skills/animejs')]);
  assert.equal(merged.defaultProvider,'custom');
  assert.equal(merged.defaultModel,'custom-model');
  assert.equal(merged.theme,'dark');
  assert(merged.packages.includes('git:github.com/example/tools'));
  assert(merged.packages.includes('npm:pi-agents@'+versions.packages['pi-agents']));
  assert(!merged.packages.includes('npm:pi-agents'));
  assert.deepEqual(merged.defaultTools,existing.defaultTools);
  assert(mergeSettings({},agent).defaultTools.includes('+codemode'));
  assert.deepEqual(mergeSettings({defaultTools:['-codemode']},agent).defaultTools,['-codemode']);
  assert.equal(mergeSettings(merged,agent,merged.skills).packages.length,merged.packages.length);
  assert.equal(mergeSettings(merged,agent,merged.skills).skills.length,merged.skills.length);
  const filtered=mergeSettings({packages:[{source:'npm:pi-agents',extensions:[],skills:[]},{source:root,extensions:['!extensions/parallel/index.ts']}]},agent);
  assert.deepEqual(filtered.packages.find(entry=>typeof entry==='object' && entry.source.startsWith('npm:pi-agents')).extensions,[]);
  assert.deepEqual(filtered.packages.find(entry=>typeof entry==='object' && entry.source===root).extensions,['!extensions/parallel/index.ts']);
  assert.throws(()=>preflight(agent,{packages:['npm:unrelated@1']},{}),/Unrelated npm/);
  await mkdir(join(agent,'extensions/chatgpt-fast'),{recursive:true});
  assert.throws(()=>preflight(agent,{},{}),/duplicate registrations/);
  await rm(join(agent,'extensions'),{recursive:true});
  await mkdir(join(agent,'extensions'));
  await writeFile(join(agent,'extensions/parallel.js'),'');
  assert.throws(()=>preflight(agent,{},{}),/duplicate registrations/);
  await rm(join(agent,'extensions'),{recursive:true});
  await mkdir(join(agent,'npm'));
  assert.throws(()=>preflight(agent,{},{}),/ownership is unknown/);
  await writeFile(join(agent,'npm/package.json'),JSON.stringify({devDependencies:{unrelated:'1'}}));
  assert.throws(()=>preflight(agent,{},{}),/devDependencies/);
  await rm(join(agent,'npm'),{recursive:true});
  const bin=join(agent,'node_modules/.bin');
  await mkdir(bin,{recursive:true});
  for(const name of ['npm','npm.cmd','pi','pi.cmd']) await writeFile(join(bin,name),'');
  for(const [name,entry] of [['npm','bin/npm-cli.js'],['@earendil-works/pi-coding-agent','dist/bundle/cli.js']]) {
    const packageDir=join(agent,'node_modules',name);
    await mkdir(join(packageDir,entry.split('/').slice(0,-1).join('/')),{recursive:true});
    await writeFile(join(packageDir,'package.json'),JSON.stringify({name,bin:{[name==='npm'?'npm':'pi']:entry}}));
    await writeFile(join(packageDir,entry),'');
  }
  assert.equal(commandPath('npm',{PATH:bin},'win32'),join(bin,'npm.cmd'));
  assert.equal(invocation('npm',['--version'],{PATH:bin},'win32').command,process.execPath);
  assert.equal(invocation('pi',['--version'],{PATH:bin},'win32').args[0],join(agent,'node_modules/@earendil-works/pi-coding-agent/dist/bundle/cli.js'));
  const originalSettings=JSON.stringify({...existing,privateCustomValue:'FAKE_PRIVATE_SETTING_MUST_NOT_APPEAR'});
  const credential='TEST_ONLY_DO_NOT_READ_OR_COPY';
  await writeFile(join(agent,'settings.json'),originalSettings);
  await writeFile(join(agent,'auth.json'),credential);
  const logs=[];
  const oldLog=console.log;
  console.log=(...args)=>logs.push(args.join(' '));
  try { await bootstrap({dryRun:true,agentDir:agent}); } finally { console.log=oldLog; }
  assert(!logs.join('\n').includes('FAKE_PRIVATE_SETTING_MUST_NOT_APPEAR'));
  assert.equal(await readFile(join(agent,'settings.json'),'utf8'),originalSettings);
  assert.equal(await readFile(join(agent,'auth.json'),'utf8'),credential);
  const files=join(temp,'files');
  await mkdir(files);
  await writeFile(join(files,'a'),'one');
  const first=await snapshotHash(files);
  await mkdir(join(files,'.git'));
  await writeFile(join(files,'.git','config'),'excluded');
  assert.equal(await snapshotHash(files),first);
  await writeFile(join(files,'a'),'two');
  assert.notEqual(await snapshotHash(files),first);
  await writeFile(join(files,'SKILL.md'),'---\nname: sample\ndescription: Original\n---\n\n## When to use\n\nOriginal introduction.\n');
  await applyCustomization({customization:{description:'Custom',whenToUse:'Custom introduction.'}},files);
  assert.match(await readFile(join(files,'SKILL.md'),'utf8'),/description: "Custom"/);
  assert.match(await readFile(join(files,'SKILL.md'),'utf8'),/Custom introduction\./);
  const manifest=JSON.parse(await readFile(join(root,'config/npm/package.json'),'utf8'));
  const lock=JSON.parse(await readFile(join(root,'config/npm/package-lock.json'),'utf8'));
  assert.deepEqual(manifest.dependencies,lock.packages[''].dependencies);
  assert.deepEqual(manifest.dependencies,versions.packages);
  for(const [name,version] of Object.entries(versions.packages)) assert.equal(lock.packages['node_modules/'+name].version,version);
  console.log('PASS setup parsing, pins, settings preservation/idempotency, duplicate guards, dry-run credential isolation, skill hashing/customization and dependency snapshot');
} finally { await rm(temp,{recursive:true,force:true}); }
